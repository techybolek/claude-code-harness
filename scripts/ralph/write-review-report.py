#!/usr/bin/env python3
"""Render a review-flow-only REVIEW_VERDICT into a readable markdown report.

The verdict used to live only in the pipeline's stdout (terminal scrollback) and
inside the 670KB stream-json session log — so escalated plan deviations became
unreadable the moment the terminal closed. This writes them next to the plan.

Usage:  write-review-report.py <out_path> <task> <branch> <base_branch> <base_ref> <timestamp>
        with the review session's final message on stdin.

Exits non-zero and writes nothing if no verdict JSON can be parsed, so the
caller can warn accurately instead of pointing at a file that does not exist.
The caller treats that as non-fatal — never break a run over a report.
"""
import json
import sys


def extract_verdict(txt):
    """Pull the first decodable JSON object after the REVIEW_VERDICT: marker."""
    i = txt.find("REVIEW_VERDICT:")
    if i < 0:
        return None
    payload = txt[i + len("REVIEW_VERDICT:"):]
    dec = json.JSONDecoder()
    for j, ch in enumerate(payload):
        if ch == "{":
            try:
                obj, _ = dec.raw_decode(payload[j:])
                return obj
            except ValueError:
                continue
    return None


def section(out, title, items, empty="_None._"):
    out.append(f"## {title}\n")
    if not items:
        out.append(empty + "\n")
        return
    for n, item in enumerate(items, 1):
        out.append(f"{n}. {item}\n")


def main():
    if len(sys.argv) < 7:
        return 2
    out_path, task, branch, base_branch, base_ref, stamp = sys.argv[1:7]

    verdict = extract_verdict(sys.stdin.read())
    if verdict is None:
        return 1

    deviations = verdict.get("planDeviations") or []
    unresolved = verdict.get("unresolvedFindings") or []
    rejected = verdict.get("triageRejected") or []
    nits = verdict.get("nits") or []

    out = [
        f"# Review findings — {task}\n",
        "_Generated by ralph-pipeline.sh. Regenerated on every review run —"
        " edits here are not preserved._\n",
        "| | |",
        "|---|---|",
        f"| Generated | {stamp} |",
        f"| Branch | `{branch}` |",
        f"| Base | `{base_branch}` @ `{base_ref[:10] if base_ref else 'n/a'}` |",
        f"| Status | {verdict.get('status', '?')} |",
        f"| Validation | {verdict.get('validation', '?')} |",
        f"| Review | {verdict.get('review', '?')} |",
        "",
    ]

    vi = verdict.get("validationIssues")
    if vi:
        out.append("## Validation issues\n")
        out.append(f"{vi}\n")

    # Deviations first: they are the only part that requires a human decision.
    out.append("## ⚠ Plan deviations — human ruling required"
               f" ({len(deviations)})\n")
    if deviations:
        out.append("The pipeline is not allowed to auto-fix these. Amend the"
                   " spec/plan, or accept the plan's letter, then rerun with"
                   " `--skip-ralph`.\n")
        for n, d in enumerate(deviations, 1):
            out.append(f"{n}. {d}\n")
    else:
        out.append("_None._\n")

    section(out, f"Unresolved findings ({len(unresolved)})", unresolved,
            "_None — the fixer resolved everything the panel confirmed._")
    section(out, f"Triage-rejected findings ({len(rejected)})", rejected,
            "_None._")
    section(out, f"Nits ({len(nits)})", nits)

    with open(out_path, "w") as fh:
        fh.write("\n".join(out).rstrip() + "\n")
    print(out_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
